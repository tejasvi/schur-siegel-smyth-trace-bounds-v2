"""Emit T86Core/Leaves.lean (core Lean) and a text list from the generator output (t86_check_ref.py): the leaves sorted by
position, the claimed lower bound of I. Untrusted hints: the checker verifies everything. Adapted from the companion
leaves generator (DEC 10^12, tiling [x_lo, x_hi] from the certificate data).
usage: python3 -I gen86_leaves.py leaves.json OUT.lean OUT.txt XLO_NUM XHI_NUM"""
import json, sys, hashlib
from fractions import Fraction as Fr
DEC = 10 ** 12
raw = open(sys.argv[1], 'rb').read(); sha = hashlib.sha256(raw).hexdigest()
d = json.loads(raw)
XLO, XHI = int(sys.argv[4]), int(sys.argv[5])
L = [(Fr(l['Xp'], DEC << l['k']), 0, l['Xp'], l['Xq'], l['k'], bool(l['x0q']), l['mask']) for l in d['chord']]
L += [(Fr(w['Xu'], DEC << w['k']), 1, w['Xu'], w['Xv'], w['k'], False, 0) for w in d['windows']]
L.sort(key=lambda t: t[0])
for a, b in zip(L, L[1:]):
    assert Fr(a[3], DEC << a[4]) == Fr(b[2], DEC << b[4]), (a, b)
assert L[0][0] == Fr(XLO, DEC), L[0]
assert Fr(L[-1][3], DEC << L[-1][4]) == Fr(XHI, DEC), L[-1]
out = ['import T86Core.Check', '',
       f'/-! Leaves of the 86a tiling, generated by tools/gen86_leaves.py from {sys.argv[1].split("/")[-1]} (sha256 {sha}). -/',
       '', 'set_option maxRecDepth 200000', 'set_option maxHeartbeats 0', '', 'namespace T86Core', '',
       f'/-- Claimed lower bound `I ≥ iLoNum / 2^128`. -/', f'def iLoNum : Nat := {d["Ilo"][0]}',
       'def leaves : List Leaf := [']
out.append(',\n'.join(f'  ⟨{t[1]}, {t[2]}, {t[3]}, {t[4]}, {"true" if t[5] else "false"}, {t[6]}⟩' for t in L))
out += [']', '', 'end T86Core', '']
open(sys.argv[2], 'w').write('\n'.join(out))
with open(sys.argv[3], 'w') as f:
    for t in L:
        f.write(f'C {t[2]} {t[3]} {t[4]} {1 if t[5] else 0} {t[6]}\n' if t[1] == 0 else f'W {t[2]} {t[3]} {t[4]}\n')
print('leaves', len(L), 'sha', sha)
